# 读取未填写的裁决表
rows = list(csv.DictReader(open(SRC, encoding='utf-8-sig')))
assert len(rows) == 176, '行数异常: %d' % len(rows)

# 按合同分组核对条数
by_contract = collections.OrderedDict()
for r in rows:
    by_contract.setdefault(r['contract_id'], []).append(r)
for cid, items in by_contract.items():
    assert len(items) == len(VERDICTS[cid]), '%s 条数不符: 表%d vs 裁决%d' % (cid, len(items), len(VERDICTS[cid]))

# 填写
for cid, items in by_contract.items():
    for item, (verdict, note) in zip(items, VERDICTS[cid]):
        item['人工裁决'] = verdict
        item['备注'] = note

# 保存
fields = ['contract_id', 'clause', 'risk_level', 'risk_type', '预分类', '人工裁决', '备注']
with open(SRC, 'w', encoding='utf-8-sig', newline='') as f:
    w = csv.DictWriter(f, fieldnames=fields)
    w.writeheader()
    w.writerows(rows)

# ===== 统计 =====
cnt = collections.Counter(r['人工裁决'] for r in rows)
print('裁决分布:', dict(cnt))

# 5条合理发现在rescored中是否仍为FP（避免与TP重复计数）
rescored = json.load(open(RESCORED, encoding='utf-8'))
rescored_fp_texts = set()
for c in rescored['per_contract']:
    for fp in c.get('false_positive', []):
        rescored_fp_texts.add((c['contract_id'], fp['clause']))
rescored_total = rescored['tp'] + rescored['fp']
still_fp = sum(1 for r in rows if r['人工裁决'] == '合理发现'
               and (r['contract_id'], r['clause']) in rescored_fp_texts)
valid = rescored['tp'] + still_fp
print('rescored口径: TP=%d, 合理发现且仍计FP=%d, 总预测=%d' % (rescored['tp'], still_fp, rescored_total))
print('真实精确率 = %d/%d = %.1f%%' % (valid, rescored_total, 100.0 * valid / rescored_total))

# 过度预警模式分布（供提示词迭代用）
def pattern(r):
    rt, cl = r['risk_type'], r['clause']
    if '0.5%' in cl or '违约金' in rt: return '违约金0.5%误报过高'
    if '押金' in rt: return '押金退还惯例表述'
    if '费用' in rt: return '费用分担惯例'
    if '维修' in rt: return '维修条款惯例'
    if '续租' in rt or '优先承租' in rt: return '续租条款惯例'
    if any(k in rt for k in ['权属', '出租权', '权利瑕疵', '权利变动', '主体资格']): return '坐落/权属惯例'
    if any(k in rt for k in ['交付', '交接', '验收']): return '交付交接惯例'
    if '送达' in rt: return '通知送达惯例'
    if any(k in rt for k in ['日期', '签署', '生效', '形式']): return '日期/签署空位'
    if any(k in rt for k in ['支付', '账户', '租金支付', '收款']): return '支付方式惯例'
    if any(k in rt for k in ['解除', '退租', '解约']): return '解除/退租惯例'
    return '其他: ' + rt

over = [r for r in rows if r['人工裁决'] == '过度预警']
pc = collections.Counter(pattern(r) for r in over)
print()
print('过度预警模式TOP（共%d条）:' % len(over))
for k, v in pc.most_common():
    print('  %s: %d' % (k, v))
